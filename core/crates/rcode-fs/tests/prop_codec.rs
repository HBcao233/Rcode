//! Property tests for the text codec.
//!
//! Three generators, all through the public API only:
//!
//! 1. arbitrary bytes: `decode` must not panic, must report a valid UTF-8
//!    prefix for [`CodecError::NotUtf8`], and must round-trip when the input
//!    is text with a single line-ending form;
//! 2. random documents (BOM, line-ending form, line contents): `decode` must
//!    match a reference normalization and `encode` a reference encoder;
//! 3. random documents with random edits: `encode` must not panic, must keep
//!    the line count and must use exactly the document's line ending.
//!
//! Failing seeds are written to `core/tests/regressions/prop_codec.txt` (see
//! `.agents/skills/testing-qa/SKILL.md`) and must be committed.

use proptest::prelude::*;
use proptest::test_runner::{Config, FileFailurePersistence};
use rcode_fs::codec::{
    CodecError, DocumentFormat, LineEnding, UnsupportedKind, decode, encode, encode_into,
};

/// UTF-8 byte order mark.
const BOM: &[u8] = &[0xEF, 0xBB, 0xBF];

/// Characters that must survive decoding: ASCII, CJK, astral-plane emoji
/// (UTF-16 surrogate pairs), combining marks, a lone `\r`, `\n\r` and Unicode
/// line separators.
///
/// `U+FEFF` is deliberately absent: a document whose text starts with it cannot
/// be told apart from a BOM-prefixed file after saving, so it is covered by the
/// unit tests and by the arbitrary-bytes generator instead.
const PIECES: &[&str] = &[
    "a", "Z", "0", " ", "\t", "\n", "\n\r", "\r", "é", "中", "文字", "🙂", "🚀", "e\u{301}",
    "\u{2028}", "\u{2029}", "",
];

fn line_content() -> impl Strategy<Value = String> {
    prop::collection::vec(prop::sample::select(PIECES), 0..4).prop_map(|pieces| pieces.concat())
}

fn line_ending() -> impl Strategy<Value = LineEnding> {
    prop_oneof![Just(LineEnding::Lf), Just(LineEnding::CrLf)]
}

fn document_format() -> impl Strategy<Value = DocumentFormat> {
    (any::<bool>(), line_ending())
        .prop_map(|(bom, line_ending)| DocumentFormat { bom, line_ending })
}

/// One generated document: its bytes and the text/format expected from them.
///
/// `format` is derived from the generated bytes with the reference rules, so a
/// line content that ends with `\r` (and therefore turns the following
/// separator into a `\r\n`) is accounted for.
#[derive(Debug, Clone)]
struct Document {
    bytes: Vec<u8>,
    text: String,
    format: DocumentFormat,
}

/// Reference decoder: strip one BOM, rewrite every `\r\n` as `\n`.
///
/// Implemented with `Vec<u8>` splicing instead of sharing code with the crate.
fn reference_body(bytes: &[u8]) -> (&[u8], bool) {
    match bytes.strip_prefix(BOM) {
        Some(body) => (body, true),
        None => (bytes, false),
    }
}

fn reference_text(bytes: &[u8]) -> String {
    let (body, _) = reference_body(bytes);
    let mut out = Vec::with_capacity(body.len());
    let mut index = 0;
    while index < body.len() {
        if body[index] == b'\r' && body.get(index + 1) == Some(&b'\n') {
            out.push(b'\n');
            index += 2;
        } else {
            out.push(body[index]);
            index += 1;
        }
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// Reference dominant line ending: majority form, ties go to the first break.
fn reference_line_ending(body: &[u8]) -> LineEnding {
    let crlf = body.windows(2).filter(|window| *window == b"\r\n").count();
    let total_lf = body.iter().filter(|&&byte| byte == b'\n').count();
    let lf = total_lf - crlf;
    if crlf > lf {
        return LineEnding::CrLf;
    }
    if lf > crlf {
        return LineEnding::Lf;
    }
    match body.iter().position(|&byte| byte == b'\n') {
        Some(0) | None => LineEnding::Lf,
        Some(index) if body[index - 1] == b'\r' => LineEnding::CrLf,
        Some(_) => LineEnding::Lf,
    }
}

/// Reference encoder: optional BOM, then `\n` replaced by the document form.
fn reference_encode(text: &str, format: &DocumentFormat) -> Vec<u8> {
    let mut out = Vec::new();
    if format.bom {
        out.extend_from_slice(BOM);
    }
    match format.line_ending {
        LineEnding::Lf => out.extend_from_slice(text.as_bytes()),
        LineEnding::CrLf => out.extend_from_slice(text.replace('\n', "\r\n").as_bytes()),
    }
    out
}

/// `true` when every line break of `body` has the same form.
fn is_uniform(body: &[u8]) -> bool {
    let crlf = body.windows(2).filter(|window| *window == b"\r\n").count();
    let total_lf = body.iter().filter(|&&byte| byte == b'\n').count();
    crlf == 0 || crlf == total_lf
}

fn document_strategy() -> impl Strategy<Value = Document> {
    (
        prop::collection::vec(line_content(), 0..8),
        document_format(),
        any::<bool>(),
    )
        .prop_map(|(lines, requested, trailing)| {
            let mut bytes = Vec::new();
            if requested.bom {
                bytes.extend_from_slice(BOM);
            }
            for (index, line) in lines.iter().enumerate() {
                bytes.extend_from_slice(line.as_bytes());
                if index + 1 < lines.len() || trailing {
                    bytes.extend_from_slice(requested.line_ending.as_bytes());
                }
            }
            let text = reference_text(&bytes);
            let format = DocumentFormat {
                bom: requested.bom,
                line_ending: reference_line_ending(&bytes),
            };
            Document {
                bytes,
                text,
                format,
            }
        })
}

/// A random edit: delete one whole line (when there is one) or append a line.
#[derive(Debug, Clone)]
enum Edit {
    DeleteLine { line: usize },
    AppendLine { text: String },
}

fn edit_strategy() -> impl Strategy<Value = Edit> {
    prop_oneof![
        (0usize..32).prop_map(|line| Edit::DeleteLine { line }),
        line_content().prop_map(|text| Edit::AppendLine { text }),
    ]
}

fn apply(edit: &Edit, text: &str) -> String {
    match edit {
        Edit::DeleteLine { line } => {
            let mut pieces: Vec<&str> = text.split('\n').collect();
            if pieces.len() > 1 && *line < pieces.len() {
                pieces.remove(*line);
            }
            pieces.join("\n")
        }
        Edit::AppendLine { text: new_line } => {
            let mut out = String::from(text);
            if !out.is_empty() && !out.ends_with('\n') {
                out.push('\n');
            }
            out.push_str(new_line);
            out
        }
    }
}

proptest! {
    #![proptest_config(Config {
        cases: 1_000,
        // `Direct` is relative to the crate root, i.e. `core/crates/rcode-fs`.
        failure_persistence: Some(Box::new(FileFailurePersistence::Direct(
            "../../tests/regressions/prop_codec.txt",
        ))),
        ..Config::default()
    })]

    #[test]
    fn arbitrary_bytes_decode_or_fail_cleanly(bytes in prop::collection::vec(any::<u8>(), 0..512)) {
        match decode(&bytes) {
            Ok(decoded) => {
                let expected_text = reference_text(&bytes);
                prop_assert_eq!(&decoded.text, &expected_text);
                prop_assert_eq!(decoded.format.bom, bytes.starts_with(BOM));
                prop_assert_eq!(decoded.format.line_ending, reference_line_ending(&bytes));
                prop_assert_eq!(&encode(&decoded.text, &decoded.format), &reference_encode(&decoded.text, &decoded.format));
                if is_uniform(&bytes) {
                    prop_assert_eq!(&encode(&decoded.text, &decoded.format), &bytes);
                }
            }
            Err(CodecError::NotUtf8 { offset }) => {
                prop_assert!(offset <= bytes.len());
                prop_assert!(std::str::from_utf8(&bytes[..offset]).is_ok());
            }
            Err(CodecError::UnsupportedEncoding { kind }) => {
                match kind {
                    UnsupportedKind::Binary { nul_offset } => {
                        prop_assert_eq!(bytes.get(nul_offset), Some(&0));
                    }
                    _ => prop_assert!(bytes.starts_with(&[0xFF, 0xFE]) || bytes.starts_with(&[0xFE, 0xFF]) || bytes.starts_with(&[0x00, 0x00, 0xFE, 0xFF])),
                }
            }
        }
    }

    #[test]
    fn documents_match_the_reference_codec(document in document_strategy()) {
        let decoded = match decode(&document.bytes) {
            Ok(decoded) => decoded,
            Err(error) => return Err(TestCaseError::fail(format!("decode failed: {error}"))),
        };
        prop_assert_eq!(&decoded.text, &document.text);
        prop_assert_eq!(&decoded.format, &document.format);
        let encoded = encode(&decoded.text, &decoded.format);
        prop_assert_eq!(&encoded, &reference_encode(&decoded.text, &decoded.format));
        // Byte-for-byte fidelity only holds when all line breaks share one form
        // (Q-T9-2: mixed files are normalised on save).
        if is_uniform(&document.bytes) {
            prop_assert_eq!(&encoded, &document.bytes);
        }

        let mut reused = Vec::new();
        encode_into(&decoded.text, &decoded.format, &mut reused);
        prop_assert_eq!(reused, encoded);
    }

    #[test]
    fn edited_documents_keep_the_line_count_and_one_ending(
        document in document_strategy(),
        edits in prop::collection::vec(edit_strategy(), 0..8),
    ) {
        let mut text = document.text;
        let format = document.format;
        for edit in &edits {
            text = apply(edit, &text);
        }

        let bytes = encode(&text, &format);
        prop_assert_eq!(&bytes, &reference_encode(&text, &format));

        let newline_count = text.matches('\n').count();
        prop_assert_eq!(bytes.iter().filter(|&&byte| byte == b'\n').count(), newline_count);
        // A `\r` stored in the text is content (for example from `a\r\r\nb`),
        // so the one-ending rule only applies to text without a `\r\n` pair.
        if !text.contains("\r\n") {
            let crlf_count = bytes.windows(2).filter(|window| *window == b"\r\n").count();
            match format.line_ending {
                LineEnding::Lf => prop_assert_eq!(crlf_count, 0),
                LineEnding::CrLf => prop_assert_eq!(crlf_count, newline_count),
            }
        }

        // Re-decoding is stable: the text comes back and the line-ending form
        // is unchanged (an empty document has no line break to report, so its
        // format collapses to the default `Lf`).
        let decoded = match decode(&bytes) {
            Ok(decoded) => decoded,
            Err(error) => return Err(TestCaseError::fail(format!("decode failed: {error}"))),
        };
        prop_assert_eq!(decoded.text.matches('\n').count(), newline_count);
        if newline_count > 0 && !text.contains("\r\n") {
            prop_assert_eq!(decoded.format.line_ending, format.line_ending);
        }
        prop_assert_eq!(decoded.format.bom, format.bom);
    }
}
