// T-0003: build the Rust core (cargo-ndk → jniLibs, UniFFI → Kotlin) before compiling Kotlin.
val buildCore by tasks.registering(Exec::class) {
    group = "rcode"
    description = "Builds core/ for arm64-v8a and regenerates UniFFI Kotlin bindings."
    workingDir = rootProject.projectDir
    val script = rootProject.file("scripts/build-core.sh")
    inputs.file(script)
    inputs.dir(rootProject.file("core/crates"))
    inputs.file(rootProject.file("core/Cargo.toml"))
    inputs.file(rootProject.file("core/Cargo.lock"))
    outputs.dir(file("src/main/jniLibs"))
    outputs.dir(layout.buildDirectory.dir("generated/uniffi/kotlin"))
    commandLine("bash", script.absolutePath)
}

tasks.named("preBuild") {
    dependsOn(buildCore)
}

// ktlint reads the generated bindings directory, so it must run after buildCore.
tasks.matching { it.name.contains("Ktlint") }.configureEach {
    dependsOn(buildCore)
}

